#!/usr/bin/env python3
"""
Where does HebNLI-15k fine-tuning lose decoder accuracy on HEntailment?
CPU only, from saved per-item predictions. Writes reverse_direction_diagnosis.md
next to this file.

For each decoder and HEntailment test set, zero-shot vs HebNLI-15k (mean over
seeds 42/43/44):
  * per-label F1 and the drop in each (the macro-F1 drop is the mean of the three);
  * share of predictions per label (against the gold share);
  * where gold-neutral rows go (neutral / entailment / contradiction);
  * entailment-vs-contradiction accuracy on gold entailment and contradiction
    rows only (a neutral prediction counts as wrong).
"""
import json, statistics as st
from collections import Counter
from pathlib import Path
E = Path(__file__).resolve().parent
R = E / "grid" / "results"
OUT = E / "reverse_direction_diagnosis.md"
DEC = [("dicta-il/DictaLM-3.0-1.7B-Instruct", "DictaLM-3.0-1.7B"), ("dicta-il/DictaLM-3.0-24B-Base", "DictaLM-3.0-24B"),
       ("HebArabNlpProject/Hebatron", "Hebatron"), ("google/gemma-4-12B-it", "gemma-4-12B"),
       ("google/gemma-4-31B-it", "gemma-4-31B"), ("Qwen/Qwen3.6-27B", "Qwen3.6-27B")]
SRC = ["heq", "qasem", "hesum", "hebsummaries", "heb_paraphrase"]
LAB = ["entailment", "contradiction", "neutral"]
def load(m, kind, ts):
    base = R / m.replace("/", "__")
    paths = [base / "zero_shot" / "predictions" / f"{ts}.jsonl"] if kind == "zs" else \
            [base / "train_hebnli_15k" / f"seed_{s}" / "predictions" / f"{ts}.jsonl" for s in (42, 43, 44)]
    return [[json.loads(l) for l in open(p, encoding="utf-8")] for p in paths if p.exists()]
def stats(rows):
    g = [r["gold"] for r in rows]; p = [r["prediction"] for r in rows]; n = len(rows)
    f1 = {}
    for l in LAB:
        tp = sum(a == l and b == l for a, b in zip(g, p)); fp = sum(a != l and b == l for a, b in zip(g, p)); fn = sum(a == l and b != l for a, b in zip(g, p))
        pr = tp / (tp + fp) if tp + fp else 0.0; rc = tp / (tp + fn) if tp + fn else 0.0
        f1[l] = 2 * pr * rc / (pr + rc) if pr + rc else 0.0
    share = {l: sum(b == l for b in p) / n for l in LAB}
    neu = [b for a, b in zip(g, p) if a == "neutral"]
    nflow = {l: (sum(b == l for b in neu) / len(neu) if neu else 0.0) for l in LAB}
    ec = [(a, b) for a, b in zip(g, p) if a in ("entailment", "contradiction")]
    return {"f1": f1, "macro": st.mean(f1.values()), "share": share, "neutral_goes": nflow, "ec_acc": sum(a == b for a, b in ec) / len(ec)}
def avg(list_of_stats):
    out = {"f1": {l: st.mean(s["f1"][l] for s in list_of_stats) for l in LAB},
           "share": {l: st.mean(s["share"][l] for s in list_of_stats) for l in LAB},
           "neutral_goes": {l: st.mean(s["neutral_goes"][l] for s in list_of_stats) for l in LAB},
           "macro": st.mean(s["macro"] for s in list_of_stats), "ec_acc": st.mean(s["ec_acc"] for s in list_of_stats)}
    return out
res = {}
for m, n in DEC:
    for ts in SRC:
        zs, ft = load(m, "zs", ts), load(m, "ft", ts)
        if zs and ft:
            res[(n, ts)] = (avg([stats(x) for x in zs]), avg([stats(x) for x in ft]))
d = lambda a, b: f"{b - a:+.2f}"
L = ["# Why HebNLI-15k fine-tuning lowers decoder scores on HEntailment (diagnosis)", "",
     "Generated by `experiments/reverse_direction_diagnosis.py` from saved predictions (seeds 42/43/44 averaged for the fine-tuned side; zero-shot has one run). "
     "Hypothesis: HebNLI's neutral class follows a different convention from HEntailment's similarity-selected neutrals.", "",
     "## 1. Per-label F1 change, zero-shot → HebNLI-15k (mean over the five HEntailment test sets)", "",
     "| decoder | Δ macro-F1 | Δ F1 entailment | Δ F1 contradiction | Δ F1 neutral | Δ ent-vs-con accuracy |", "|---|---|---|---|---|---|"]
summ = {}
for m, n in DEC:
    rows = [res[(n, ts)] for ts in SRC if (n, ts) in res]
    if not rows:
        continue
    dm = st.mean(b["macro"] - a["macro"] for a, b in rows)
    dl = {l: st.mean(b["f1"][l] - a["f1"][l] for a, b in rows) for l in LAB}
    de = st.mean(b["ec_acc"] - a["ec_acc"] for a, b in rows)
    summ[n] = (dm, dl, de)
    L.append(f"| {n} | {dm:+.3f} | {dl['entailment']:+.3f} | {dl['contradiction']:+.3f} | {dl['neutral']:+.3f} | {de:+.3f} |")
allm = st.mean(v[0] for v in summ.values()); alll = {l: st.mean(v[1][l] for v in summ.values()) for l in LAB}
L += [f"| **mean of decoders** | {allm:+.3f} | {alll['entailment']:+.3f} | {alll['contradiction']:+.3f} | {alll['neutral']:+.3f} | {st.mean(v[2] for v in summ.values()):+.3f} |", ""]
L += ["## 2. Where gold-neutral items go (share of gold-neutral rows), zero-shot → HebNLI-15k, mean over test sets", "",
      "| decoder | neutral kept (zs → ft) | sent to entailment | sent to contradiction |", "|---|---|---|---|"]
for m, n in DEC:
    rows = [res[(n, ts)] for ts in SRC if (n, ts) in res]
    if not rows:
        continue
    g = lambda i, l: st.mean(r[i]["neutral_goes"][l] for r in rows)
    L.append(f"| {n} | {g(0,'neutral'):.2f} → {g(1,'neutral'):.2f} | {g(0,'entailment'):.2f} → {g(1,'entailment'):.2f} | {g(0,'contradiction'):.2f} → {g(1,'contradiction'):.2f} |")
L += ["", "## 3. Share of predictions per label (gold: entailment 43%, neutral 39%, contradiction 18% over the corpus)", "",
      "| decoder | entailment (zs → ft) | neutral (zs → ft) | contradiction (zs → ft) |", "|---|---|---|---|"]
for m, n in DEC:
    rows = [res[(n, ts)] for ts in SRC if (n, ts) in res]
    if not rows:
        continue
    g = lambda i, l: st.mean(r[i]["share"][l] for r in rows)
    L.append(f"| {n} | {g(0,'entailment'):.2f} → {g(1,'entailment'):.2f} | {g(0,'neutral'):.2f} → {g(1,'neutral'):.2f} | {g(0,'contradiction'):.2f} → {g(1,'contradiction'):.2f} |")
L += ["", "## 4. Per decoder and test set: Δ macro-F1 and Δ F1 per label", "", "| decoder | test set | Δ macro | Δ ent | Δ con | Δ neu |", "|---|---|---|---|---|---|"]
for m, n in DEC:
    for ts in SRC:
        if (n, ts) in res:
            a, b = res[(n, ts)]
            L.append(f"| {n} | {ts} | {b['macro'] - a['macro']:+.3f} | {d(a['f1']['entailment'], b['f1']['entailment'])} | {d(a['f1']['contradiction'], b['f1']['contradiction'])} | {d(a['f1']['neutral'], b['f1']['neutral'])} |")
OUT.write_text("\n".join(L) + "\n", encoding="utf-8")
print("\n".join(L[:34]))
