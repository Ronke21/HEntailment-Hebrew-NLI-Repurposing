"""
Task 2 — Hebrew Winograd Schema Challenge Conversion
Entailment/contradiction hypotheses generated by Gemini from (context, question, answer option).
Neutral: cross-schema hypothesis from same split.
80/10/10 split keeping both variants of a schema pair in the same split.
Skips splits whose output JSONL already exists.
"""

import argparse
import json
import random
import re
import sys
import time
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from utils.gemini_utils import batch_generate
from utils.logging_utils import (setup_logging, is_split_done, log_label_stats, log_examples,
                                  length_ok, log_length_rejections)

import logging
logger = logging.getLogger(__name__)

# Prompt: generate a BARE DECLARATIVE fact — no meta-commentary about answers/correctness.
# 78% of prior outputs started with "נכון," or "התשובה" which the model reads as
# neutral meta-commentary rather than a factual contradiction of the premise.
# Matrix-verb rule added: if the context contains a verb like הכריז/מקווה/חושב + ש,
# the hypothesis must preserve the full structure (subject + matrix verb + ש + clause)
# to prevent bare-clause stripping that loses the epistemic frame.
WINOGRAD_HYP_PROMPT = (
    "קיבלת משפט עברי ושאלה לגביו. כתוב משפט עברי אחד קצר שמצהיר ישירות שהתשובה היא '{answer}'.\n"
    "כללים חשובים:\n"
    "- אל תכתוב 'נכון' או 'שגוי'\n"
    "- אל תכתוב 'התשובה' או 'הכוונה'\n"
    "- אל תכתוב 'אכן' או 'זה נכון'\n"
    "- כתוב עובדה ישירה בלבד, כאילו אתה מספר מה קרה\n"
    "- דוגמה טובה: 'דינה היא שפתחה את הדלת' ולא 'נכון, דינה פתחה'\n"
    "- אם המשפט מכיל פועל כמו 'הכריז ש', 'מקווה ש', 'חושב ש' — שמור על המבנה המלא: נושא + פועל + ש + תוכן\n\n"
    "משפט: {context}\n"
    "שאלה: {question}\n"
    "תשובה: {answer}"
)

# Matrix verbs that introduce embedded clauses via ש
_MATRIX_RE = re.compile(
    r'(.+?(?:הכריז|הודיע|מקווה|חושב|אמר|סיפר|הצהיר|ידע|האמין)\s+ש)(.+?)(?:\.|$)',
    re.UNICODE
)


def _repair_matrix_hyp(premise: str, hypothesis: str) -> str:
    """If premise has MATRIX_VERB+ש frame and hypothesis is the bare embedded clause,
    reconstruct full proposition: matrix_prefix + ש + hypothesis."""
    m = _MATRIX_RE.search(premise)
    if not m:
        return hypothesis
    matrix_prefix = m.group(1).strip()   # e.g. "בני הכריז ש"
    embedded_raw  = m.group(2).strip()   # e.g. "הוא המנצח בתחרות"
    # If matrix verb already in hypothesis, nothing to repair
    if any(v in hypothesis for v in ("הכריז","הודיע","מקווה","חושב","אמר","סיפר","הצהיר","ידע","האמין")):
        return hypothesis
    # Compute word-level overlap between hypothesis and embedded clause
    h_words = set(hypothesis.rstrip('.').split())
    e_words = set(embedded_raw.split())
    overlap = len(h_words & e_words) / max(len(h_words), 1)
    if overlap >= 0.4:
        repaired = matrix_prefix + hypothesis.rstrip('.')
        if not repaired.endswith('.'):
            repaired += '.'
        return repaired
    return hypothesis


def detect_schema_pairs(examples: list[dict]) -> tuple[dict[int, list[int]], list[int]]:
    groups: dict[str, list[int]] = defaultdict(list)
    for i, ex in enumerate(examples):
        groups[ex["context"][:40]].append(i)

    pairs, ungrouped = {}, []
    pair_id = 0
    for indices in groups.values():
        if len(indices) == 2:
            pairs[pair_id] = indices
            pair_id += 1
        else:
            ungrouped.extend(indices)

    logger.info(f"Schema pairs detected: {pair_id} | ungrouped: {len(ungrouped)}")
    return pairs, ungrouped


def assign_splits(pairs: dict, ungrouped: list, rng: random.Random) -> dict[int, str]:
    pair_ids = list(pairs.keys())
    rng.shuffle(pair_ids)
    n_train = int(len(pair_ids) * 0.8)
    n_dev   = int(len(pair_ids) * 0.1)

    assignment: dict[int, str] = {}
    for pid in pair_ids[:n_train]:
        for idx in pairs[pid]: assignment[idx] = "train"
    for pid in pair_ids[n_train:n_train+n_dev]:
        for idx in pairs[pid]: assignment[idx] = "dev"
    for pid in pair_ids[n_train+n_dev:]:
        for idx in pairs[pid]: assignment[idx] = "test"

    ug = list(ungrouped)
    rng.shuffle(ug)
    ug_train = int(len(ug) * 0.8)
    ug_dev   = int(len(ug) * 0.1)
    for idx in ug[:ug_train]:                assignment[idx] = "train"
    for idx in ug[ug_train:ug_train+ug_dev]: assignment[idx] = "dev"
    for idx in ug[ug_train+ug_dev:]:         assignment[idx] = "test"
    return assignment


def build_rows(examples: list[dict], assignment: dict, rng: random.Random,
               ent_hyps: list[str], con_hyps: list[str]) -> list[dict]:
    rows = []
    rejected: dict[str, int] = {}
    for i, ex in enumerate(examples):
        split   = assignment.get(i, "train")
        premise = ex["context"]
        base    = {"premise": premise, "dataset": "winograd", "split": split}
        e_hyp   = _repair_matrix_hyp(premise, (ent_hyps[i] or "").strip())
        c_hyp   = _repair_matrix_hyp(premise, (con_hyps[i] or "").strip())

        if e_hyp:
            if length_ok(premise, e_hyp):
                rows.append({**base, "id": f"winograd_{i:04d}_E",
                             "hypothesis": e_hyp, "label": "entailment"})
            else:
                rejected["entailment"] = rejected.get("entailment", 0) + 1
        if c_hyp:
            if length_ok(premise, c_hyp):
                rows.append({**base, "id": f"winograd_{i:04d}_C",
                             "hypothesis": c_hyp, "label": "contradiction"})
            else:
                rejected["contradiction"] = rejected.get("contradiction", 0) + 1

        # Neutral: entailment hypothesis from a different example in the same split
        candidates = [
            j for j in range(len(examples))
            if j != i and assignment.get(j) == split and (ent_hyps[j] or "").strip()
        ]
        if candidates:
            j = rng.choice(candidates)
            n_hyp = ent_hyps[j].strip()
            if length_ok(premise, n_hyp):
                rows.append({**base, "id": f"winograd_{i:04d}_N",
                             "hypothesis": n_hyp, "label": "neutral"})
            else:
                rejected["neutral"] = rejected.get("neutral", 0) + 1

    if rejected:
        logger.info(f"Length-filter rejected: {dict(rejected)}")
    return rows


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--data_file",    required=True)
    parser.add_argument("--output_dir",   required=True)
    parser.add_argument("--log_dir",      default="logs")
    parser.add_argument("--random_state", type=int, default=42)
    parser.add_argument("--smoke", type=int, default=0,
                        help="Smoke-test mode: limit to N examples (0=disabled)")
    args = parser.parse_args()

    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    setup_logging(Path(args.log_dir), "07_winograd_convert")
    logger.info(f"Winograd conversion started | data={args.data_file}"
                + (f" | SMOKE={args.smoke}" if args.smoke else ""))

    if all(is_split_done(output_dir, s) for s in ["train", "dev", "test"]):
        logger.info("All splits already complete. Nothing to do.")
        return

    t0 = time.time()
    examples = []
    with open(args.data_file, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line:
                examples.append(json.loads(line))
    if args.smoke > 0:
        rng_smoke = random.Random(42)
        examples = rng_smoke.sample(examples, min(args.smoke, len(examples)))
        logger.info(f"SMOKE MODE: {len(examples)} examples")
    logger.info(f"Loaded {len(examples)} examples")

    # Generate hypotheses with Gemini
    items_ent = [
        {"context": ex["context"], "question": ex["question"],
         "answer": ex["option1"] if ex["label"] == 1 else ex["option2"]}
        for ex in examples
    ]
    items_con = [
        {"context": ex["context"], "question": ex["question"],
         "answer": ex["option2"] if ex["label"] == 1 else ex["option1"]}
        for ex in examples
    ]

    logger.info(f"Calling Gemini for entailment hypotheses ({len(items_ent)} items)...")
    t1 = time.time()
    ent_hyps = batch_generate(items_ent, WINOGRAD_HYP_PROMPT,
                               output_dir / "gemini_ent_cache.json")
    logger.info(f"Entailment hypotheses done: {sum(1 for h in ent_hyps if h)} non-empty | {time.time()-t1:.1f}s")

    logger.info(f"Calling Gemini for contradiction hypotheses ({len(items_con)} items)...")
    t2 = time.time()
    con_hyps = batch_generate(items_con, WINOGRAD_HYP_PROMPT,
                               output_dir / "gemini_con_cache.json")
    logger.info(f"Contradiction hypotheses done: {sum(1 for h in con_hyps if h)} non-empty | {time.time()-t2:.1f}s")

    rng = random.Random(args.random_state)
    pairs, ungrouped = detect_schema_pairs(examples)
    assignment = assign_splits(pairs, ungrouped, rng)
    all_rows = build_rows(examples, assignment, rng, ent_hyps, con_hyps)

    split_rows: dict[str, list] = {"train": [], "dev": [], "test": []}
    for row in all_rows:
        split_rows[row["split"]].append(row)

    total = 0
    for split, rows in split_rows.items():
        if is_split_done(output_dir, split):
            continue
        out_path = output_dir / f"{split}.jsonl"
        with out_path.open("w", encoding="utf-8") as f:
            for row in rows:
                f.write(json.dumps(row, ensure_ascii=False) + "\n")
        log_label_stats(logger, rows, split, "winograd")
        log_examples(logger, rows, split)
        logger.info(f"[{split}] Wrote {len(rows):,} rows → {out_path}")
        total += len(rows)

    logger.info(f"Winograd done. Total NLI rows: {total:,} | {time.time()-t0:.1f}s")


if __name__ == "__main__":
    main()
